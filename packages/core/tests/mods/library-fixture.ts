/** Gives the imported package the library, as if it had come with it. */
export async function withHarbourLibrary(mod: Mod): Promise<void> {
  for (const [file, content] of Object.entries(LIBRARY_FILES)) await put(path.join(mod.modPackage, ...file.split("/")), content);
}
